# -*- coding: utf-8 -*-
"""نرمال‌ساز متن فارسی برای کامنت‌ها.

این ماژول یک تابع *خالص* است: ورودی متن، خروجی متن. هیچ‌جای دیگری نباید
عربی→فارسی، اعراب یا ایموجی را دست بزند، وگرنه آموزش و پیش‌بینی می‌توانند
متن یکسان را دوگونه ببینند.

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
یافته‌های Audit — چرا هر مرحله اینجاست
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

نسخهٔ پیشین این چهار مشکل را داشت. هرکدام با یک ورودی واقعی پیدا شد:

۱) **حرف تکراری به دو حرف تا می‌خورد، نه یکی.** ``عاااااااالی`` به ``عاالی``
   تبدیل می‌شد — واژهٔ بی‌معنا که در واژگان مدل نیست. یعنی تأکید («خیلی خوب»
   که به شکل ``خوووووب`` نوشته می‌شود) سیگنالش را کامل از دست می‌داد. حالا
   سه تکرار و بیشتر به *یک* حرف می‌رسد تا ``عالی`` بازیابی شود. دو تکرار دست
   نمی‌خورد، چون فارسی دو حرف پشت‌سرهمِ درست هم دارد (``الله``).

۲) **ایموجی حذف می‌شد.** ``👍`` و ``👎`` قوی‌ترین سیگنال احساسی بعضی کامنت‌ها
   هستند و کامنت‌های فقط‌ایموجی بعد از حذف، **بردار ویژگی خالی** می‌دادند؛
   مدل روی بردار خالی هم یک برچسب با اطمینان عددی برمی‌گرداند و کاربر فکر
   می‌کرد نتیجه معنادار است. حالا ایموجی‌های رایج به واژهٔ فارسی نگاشته
   می‌شوند و بردار خالی به‌عنوان «سیگنال ناکافی» شناسایی می‌شود.

۳) **نشانی وب و منشن به توکن‌های آشغال بدل می‌شدند.** ``https://x.com`` به سه
   توکن ``https``، ``x``، ``com`` تبدیل می‌شد. حالا نشانی کامل و ``@منشن``
   حذف می‌شوند (هشتگ می‌ماند، چون واژه‌اش محتواست).

۴) **غلط‌های تایپی رایج اصلاح نمی‌شدند.** ``خيلي`` با نگاشت حروف درست می‌شد،
   ولی ``عاليه`` واژهٔ ناشناس می‌ماند. حالا یک جدول صریح از غلط‌های پرتکرار
   وجود دارد — و **همان جدول** منبع تزریق نویز در دیتاست آموزش هم هست، پس مدل
   روی همان چیزی تمرین می‌کند که نرمال‌ساز اصلاح می‌کند.

۵) **ایستاها واژه‌های احساسی را می‌خوردند.** ``خوبه`` و ``می‌ارزه`` در فهرست
   ایستا بودند؛ یعنی مدل قوی‌ترین واژهٔ مثبت جمله را نمی‌دید. حالا فهرست ایستا
   فقط واژه‌های نقشی دارد.
"""
from __future__ import annotations

import re

# ------------------------------------------------------------------ نگاشت حروف
#: عربی → فارسی. حرف ``ة`` به ``ه`` و ``ي``/``ك`` به شکل فارسی.
AR_TO_FA = str.maketrans({
    "ي": "ی", "ى": "ی", "ك": "ک", "ڪ": "ک", "ۀ": "ه", "ة": "ه",
    "أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ٲ": "ا", "ٳ": "ا",
    # ``ئ`` و ``ؤ`` عمداً نگاشت نمی‌شوند: حرف درست فارسی‌اند و تبدیلشان واژه را
    # خراب می‌کند («مسئولیت» → «مسیولیت» که واژه نیست). نسخهٔ پیشین هر دو را
    # نگاشت می‌کرد و همین اتفاق می‌افتاد.
    "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
    "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
    "۰": "0", "۱": "1", "۲": "2", "۳": "3", "۴": "4",
    "۵": "5", "۶": "6", "۷": "7", "۸": "8", "۹": "9",
})

DIACRITICS = re.compile("[\u064B-\u065F\u0670\u06D6-\u06ED]")
URL = re.compile(r"(?:https?://|www\.)\S+", re.IGNORECASE)
MENTION = re.compile(r"@[\w.]+")
#: حروف خط فارسی/عربی — پ + چ + ژ + ک + گ + ی در ادامهٔ بازهٔ حروف عربی.
ARABIC_LETTER = "\u0621-\u064a\u067e\u0686\u0698\u06a9\u06af\u06cc"

#: سه تکرار و بیشتر → یک حرف، **فقط داخل خط فارسی/عربی**. دو تکرار دست نمی‌خورد.
#:
#: محدودکردن به خط فارسی از یک اشکال واقعی آمده: با الگوی عام ``(.)\1{2,}``،
#: واژه‌های لاتین هم خرد می‌شدند (``zzzz`` → ``z``) و توکن‌هایی مثل کد محصول یا
#: نام برند بی‌صدا خراب می‌شدند. تکرار حرف کشیدن در فارسی معنا دارد؛ در لاتین
#: بخشی از خودِ واژه است.
REPEATS = re.compile(rf"([{ARABIC_LETTER}])\1{{2,}}")
#: نیم‌فاصله (U+200C) و فاصلهٔ مجازی عربی (U+200F) در متن می‌مانند.
PUNCT = re.compile(r"[^\w\s\u200c]")
SPACES = re.compile(r"[ \t\u00a0]+")

# ------------------------------------------------------------------ ایموجی
#: ایموجی‌های احساسی رایج → واژهٔ فارسی. فقط ایموجی‌هایی اینجا می‌آیند که
#: معنی‌شان در کامنت فارسی روشن است. ایموجی‌های خنثی/تزئینی (مثل ✨ یا 🎁)
#: نگاشته نمی‌شوند تا سیگنالی از خودشان ساخته نشود.
EMOJI_LEXICON: dict[str, str] = {
    "👍": "خوب", "👌": "خوب", "💯": "عالی", "🔥": "عالی", "❤️": "عالی",
    "❤": "عالی", "😍": "عالی", "😊": "خوب", "🙂": "خوب", "😃": "خوب",
    "🎉": "خوب", "💪": "خوب", "🙏": "ممنون",
    "👎": "بد", "😡": "بد", "😠": "بد", "🤬": "بد", "😞": "بد",
    "😔": "بد", "🙁": "بد", "☹️": "بد", "☹": "بد", "😢": "بد",
    "😭": "بد", "💔": "بد", "🤮": "بد", "❌": "بد",
    "😐": "معمولی", "🤔": "شاید", "😕": "معمولی",
}

# ------------------------------------------------------------------ غلط تایپی
#: غلط‌های پرتکرار فارسی → شکل درست.
#:
#: **یک منبع حقیقت:** ``dataset.py`` همین جدول را می‌خواند و وارونه‌اش را به
#: متن تزریق می‌کند. پس مدل روی همان غلطی تمرین می‌کند که نرمال‌ساز می‌شناسد؛
#: اگر یکی عوض شود، آن یکی هم عوض می‌شود.
#: شکل‌های *پس از* نگاشت حروف. نکته: کلیدهایی که با خط عربی نوشته می‌شوند
#: (مثل «خيلى») هیچ‌وقت به این مرحله نمی‌رسند چون ``AR_TO_FA`` پیش‌تر درستشان
#: می‌کند؛ پس اینجا فقط غلط‌های *فارسی‌خط* می‌آیند.
#:
#: هر کلید باید یک شکل نادرست باشد. اگر کلیدی زیررشتهٔ واژهٔ درستی باشد (مثل
#: «خلی» در «خلیج»)، اصلاح آن واژه را خراب می‌کند — عمداً جایی در این جدول
#: ندارند.
TYPOS: dict[str, str] = {
    # غلط‌های نگارشی رایج
    "چیزه": "چیزی", "عالیه": "عالی", "بدد": "بد", "خوبب": "خوب",
    "خوبیی": "خوبی", "ممنونمم": "ممنون",
    # شکل‌های محاوره‌ای که یک‌دست می‌شوند تا TF-IDF واژه‌های کمتری ببیند
    "ارساله": "ارسال", "کیفیتش": "کیفیت", "قیمتش": "قیمت",
    "بسته بندی": "بسته‌بندی", "رنگش": "رنگ", "سایزش": "سایز",
}

#: شکل‌های عربی هر حرف فارسی — منبع تزریق نویز در دیتاست آموزش.
#:
#: تایپ با صفحه‌کلید عربی رایج‌ترین منبع ناهمگونی در متن فارسی است. ``dataset``
#: همین جدول را می‌خواند تا نویزی بسازد که نرمال‌ساز واقعاً می‌تواند تشخیص
#: دهد — نه نویز تصادفی که کسی اصلاحش نمی‌کند.
ARABIC_VARIANTS: dict[str, tuple[str, ...]] = {
    "ی": ("ي", "ى"),
    "ک": ("ك",),
    "ه": ("ة",),
}

#: واژه‌های ایستا. **نکتهٔ مهم:** واژه‌های باردار احساسی نباید اینجا باشند.
#: در نسخهٔ پیشین ``خوبه`` و ``می‌ارزه`` در این فهرست بودند و حذف می‌شدند —
#: یعنی مدل قوی‌ترین واژهٔ مثبت جمله را نمی‌دید.
STOPWORDS = frozenset({
    "و", "در", "به", "از", "که", "این", "آن", "را", "با", "برای", "تا",
    "هم", "یک", "یکی", "من", "شما", "او", "خود", "همه", "اما", "ولی",
    "اگر", "چون", "پس", "بعد", "قبل", "روی", "زیر", "بین", "هست",
    "است", "بود", "شد", "کرد", "کنم", "کنه", "بشه", "باشه", "داره", "دارد",
    "های", "ها", "دیگه", "دیگر", "فقط", "همین", "همون",
    "چی", "چه", "کجا", "کی", "چطور", "چقدر", "بله", "آره",
    "the", "and", "for", "with", "was", "were", "are", "this", "that",
    "from", "have", "has", "but", "you", "your",
})

# ------------------------------------------------------------------ نفی
#: نشانه‌های نفی. در فارسی نفی دو جا می‌نشیند: پیش از فعل (``نمی‌کنم``، ``ندارم``)
#: و پس از صفت در ساخت‌های اسنادی (``ناراحت نشدم``، ``مشکلی نداشت``).
#:
#: **چرا نشانه‌گذاری لازم است:** مدل کیسهٔ‌واژه نمی‌فهمد که «نشدم» صفت پیش از
#: خودش را برمی‌گرداند. بدون نشانه‌گذاری، ``ناراحت نشدم`` و ``ناراحت شدم``
#: تقریباً یک بردار می‌دهند و مدل آن‌ها را یکسان می‌خواند. با نشانه‌گذاری،
#: توکن ``ن_ناراحت`` ساخته می‌شود — ویژگی مستقلی که دیتاست آموزش هم دارد.
NEGATORS = frozenset({
    "نه", "نیست", "نیستم", "نیستی", "نیستن", "نبود", "نبودم", "نبودن",
    "نشد", "نشده", "نشدم", "نشدن", "نشه", "نمیشه", "نمیشد", "نمیشود",
    "ندارد", "نداره", "ندارم", "نداری", "نداشت", "نداشتم", "نداشتن",
    "نکرد", "نکرده", "نکردم", "نکنم", "نکن", "نکنه", "نکنید",
    "نرسید", "نرسیده", "نگرفت", "نگرفتم", "نگیر", "نخردیم", "نخریدم",
    "نمیکنم", "نمیکنه", "نمیدم", "نمیدونم", "نمی‌خوام", "نمی‌کنم",
    "نمی", "بدون", "بی",
})

#: پیشوند توکن منفی‌شده. دو حرف است تا با هیچ واژهٔ واقعی فارسی اشتباه نشود
#: (خط تیره در فارسی داخل واژه نمی‌آید).
NEG_TAG = "نـ"


def _tag_negation(tokens: list[str]) -> list[str]:
    """توکنی که زیر نفی است با پیشوند ``NEG_TAG`` علامت می‌خورد.

    هر نشانهٔ نفی، هم توکن *پیش* و هم توکن *پسِ* خود را علامت می‌زند؛ چون در
    فارسی هر دو ترتیب رخ می‌دهد. خودِ نشانه هم سر جایش می‌ماند تا وجود نفی
    خودش یک ویژگی باشد.
    """
    out: list[str] = []
    for index, token in enumerate(tokens):
        if token in NEGATORS:
            out.append(token)
            continue
        before = tokens[index - 1] if index else ""
        after = tokens[index + 1] if index + 1 < len(tokens) else ""
        if before in NEGATORS or after in NEGATORS:
            out.append(NEG_TAG + token)
        else:
            out.append(token)
    return out


def normalize(text: object) -> str:
    """متن خام → متن نرمال‌شده برای بردارسازی.

    ترتیب مراحل مهم است: نشانی و منشن پیش از تبدیل ایموجی حذف می‌شوند (وگرنه
    ایموجی چسبیده به نشانی نگاشته می‌شود)، و ایموجی پیش از حذف علائم نگاشته
    می‌شود (وگرنه با علائم پاک می‌شود).
    """
    if text is None:
        return ""
    s = str(text)
    if not s:
        return ""
    s = URL.sub(" ", s)
    s = MENTION.sub(" ", s)
    s = s.translate(AR_TO_FA)
    s = DIACRITICS.sub("", s)
    s = _apply_emoji(s)
    s = REPEATS.sub(r"\1", s)
    s = PUNCT.sub(" ", s)
    s = SPACES.sub(" ", s)
    return s.strip()


def _apply_emoji(text: str) -> str:
    """ایموجی‌های احساسی با واژهٔ فارسی جانشین می‌شوند."""
    if not any(ch in text for ch in EMOJI_LEXICON):
        return text
    out = []
    for char in text:
        replacement = EMOJI_LEXICON.get(char)
        out.append(f" {replacement} " if replacement else char)
    return "".join(out)


def repair(text: str) -> str:
    """اصلاح غلط‌های تایپی جدول ``TYPOS`` روی متن نرمال‌شده.

    جدا از ``normalize`` نگه داشته شده چون بار محاسباتی دارد و در مسیرهایی
    که فقط به متن نرمال نیاز دارند (مثل نمایش متن پاک‌شده) لازم نیست.
    """
    if not text:
        return ""
    for wrong, right in TYPOS.items():
        if wrong in text and wrong != right:
            text = text.replace(wrong, right)
    return SPACES.sub(" ", text).strip()


def clean(text: object) -> str:
    """متن کامل پاک‌شده — نرمال‌سازی + اصلاح غلط. برای نمایش."""
    return repair(normalize(text))


def tokenize(text: object) -> list[str]:
    """توکن‌های معنادار — نرمال‌سازی، اصلاح غلط، حذف ایستاها.

    نیم‌فاصله اینجا شکسته می‌شود (``می‌خواهم`` → ``می`` + ``خواهم``)، چون
    TF-IDF روی توکن کار می‌کند نه روی واژهٔ چسبیده.
    """
    cleaned = clean(text)
    if not cleaned:
        return []
    surface = [raw.strip() for raw
               in cleaned.replace("\u200c", " ").replace("\u200f", " ").split()
               if raw.strip()]
    # نشانه‌گذاری نفی *پیش از* حذف ایستاها انجام می‌شود؛ وگرنه ممکن است نشانه در
    # همان مرحله پاک شود و نفی اثری نگذارد.
    tokens = []
    for token in _tag_negation(surface):
        bare = token.lstrip(NEG_TAG)
        if len(bare) < 2:
            continue
        if bare in STOPWORDS:
            continue
        if bare.isdigit():
            continue
        tokens.append(token)
    return tokens


def normalize_digits(text: object) -> str:
    """تنها تبدیل رقم‌ها — برای نمایش یکدست در رابط."""
    return str(text or "").translate(AR_TO_FA).translate(
        str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹"))
